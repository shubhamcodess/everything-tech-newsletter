"""The edition data contract: what an edition is, as models.

Two shapes, because an edition exists in two stages:

  DraftEdition      what the routine writes to data/draft.md (and what a structured-
                    output API call would have to return): only the parts that need
                    judgment -- ids, topic, signal, event, headline, dek, body, takeaways.
  PublishedEdition  the durable record, editions/<date>/edition.md, with everything
                    publish_edition.py fills in: links, authors, images, read times.

The models own *structure*: which fields exist, their types, lengths and allowed
values. They do not own *content rules* that need context or judgment (is this id a
real candidate, does the text copy the article, is it filler, is the topic one of the
configured labels); those stay in edition_schema.py.

schema_version
  Editions carry `schema_version` in their front matter. Editions written before the
  field existed have none and are version 0. Version 1 is the same shape as 0, now
  written down and enforced. migrate() upgrades older data in memory when it is read;
  the files in editions/ are never rewritten. To change the format:
    - adding an optional field: no bump, the schema and its export just grow;
    - anything that would make an older edition invalid: bump SCHEMA_VERSION, add a
      step to migrate(), and add a fixture for the old shape in tests/.

JSON Schema for non-Python consumers is generated by scripts/export_schema.py.
"""
import os
import sys
from typing import Annotated, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, StrictInt, StringConstraints, ValidationError

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dedupe import event_problem  # noqa: E402

SCHEMA_VERSION = 1
SIGNALS = ("must-read", "recommended", "notable")

# strict: a number is not a string, so 12345 can't pass as a headline
Text = Annotated[str, StringConstraints(strict=True, strip_whitespace=True)]


def text(min_length=1, max_length=None):
    return Annotated[str, StringConstraints(strict=True, strip_whitespace=True,
                                            min_length=min_length, max_length=max_length)]


class SchemaVersionError(ValueError):
    pass


# --------------------------------------------------------------------- draft

class DraftStory(BaseModel):
    """One story as the routine writes it. Unknown keys are ignored, not rejected:
    the draft format lets the author include fields (url, image, ...) that publishing
    overwrites anyway."""
    model_config = ConfigDict(extra="ignore")

    ids: list[StrictInt] = Field(min_length=1, description="Candidate ids from data/candidates.md; the cluster's lead id first.")
    topic: text(1) = Field(description="One of the labels in config/interests.json.")
    signal: Literal["must-read", "recommended", "notable"]
    event: text(1) = Field(description="3-6 lowercase keywords naming what happened; used to recognise a repeat tomorrow.")
    headline: text(15, 130)
    dek: text(40) = Field(description="One sentence under the headline that adds what the headline doesn't.")
    body: list[text(80)] = Field(min_length=1, max_length=6, description="1-6 paragraphs of prose.")
    takeaways: list[text(15)] = Field(default_factory=list, max_length=5)


class DraftEdition(BaseModel):
    model_config = ConfigDict(extra="ignore")

    brief: list[text(20)] = Field(min_length=3, max_length=6, description="3-6 bullets: the day's themes.")
    stories: list[DraftStory] = Field(min_length=1)


# ----------------------------------------------------------------- published

class Source(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: text(1)
    url: Text
    via: Optional[Text] = None


class PublishedStory(BaseModel):
    model_config = ConfigDict(extra="forbid")

    headline: text(1)
    dek: text(1)
    body: list[Text] = Field(min_length=1)
    takeaways: list[Text] = Field(default_factory=list)
    topic: text(1)
    signal: Literal["must-read", "recommended", "notable"]
    ids: list[StrictInt] = Field(default_factory=list)
    # optional: editions published before the field existed have none
    event: Optional[Text] = None
    url: Annotated[str, StringConstraints(strict=True, pattern=r"^https?://")]
    source_title: Optional[Text] = None
    sources: list[Source] = Field(min_length=1)
    author: Optional[Text] = None
    image: Optional[Text] = None
    read_minutes: Optional[StrictInt] = None
    discuss_url: Optional[Text] = None
    discuss_via: Optional[Text] = None
    points: Optional[StrictInt] = None
    comments: Optional[StrictInt] = None
    full_text: bool = False


class PublishedEdition(BaseModel):
    model_config = ConfigDict(extra="forbid")

    schema_version: Literal[1] = SCHEMA_VERSION
    date: text(1)
    edition: StrictInt
    generated_at: Optional[Text] = None
    sources_ok: Optional[StrictInt] = None
    sources_total: Optional[StrictInt] = None
    fetched: Optional[StrictInt] = None
    candidates: Optional[StrictInt] = None
    full_text: Optional[StrictInt] = None
    brief: list[Text]
    stories: list[PublishedStory]


# ------------------------------------------------------------------ versions

def migrate(data):
    """Brings an edition dict (as edition_md.parse returns it) up to SCHEMA_VERSION.
    Returns a new dict; never mutates the input."""
    version = data.get("schema_version", 0)
    if not isinstance(version, int) or version < 0:
        raise SchemaVersionError(f"schema_version must be a whole number, got {version!r}")
    if version > SCHEMA_VERSION:
        raise SchemaVersionError(f"edition has schema_version {version} but these scripts understand up to "
                                 f"{SCHEMA_VERSION} -- update the scripts")
    if version == 0:
        # 0 -> 1: no change of shape. Version 1 writes down what 0 already was.
        upgraded = {}
        for key, value in data.items():
            upgraded[key] = value
            if key == "edition":
                upgraded["schema_version"] = 1  # same place new editions carry it
        upgraded.setdefault("schema_version", 1)
        return upgraded
    return dict(data)


# ------------------------------------------------------------ error wording

def _path(loc):
    out = ""
    for part in loc:
        out += f"[{part}]" if isinstance(part, int) else (f".{part}" if out else str(part))
    return out


def _is_list_level(error, drop_prefixes):
    return any(tuple(error["loc"][:len(p)]) == p and len(error["loc"]) > len(p) for p in drop_prefixes)


def _length_errors(draft):
    """Pydantic skips a list's length check when an item inside it is invalid, but the
    routine should be told about the length first (and only), so check it directly."""
    out = []

    def bad(loc):
        out.append({"loc": loc, "type": "too_short", "msg": "wrong number of items", "input": None})

    brief = draft.get("brief")
    if isinstance(brief, list) and not 3 <= len(brief) <= 6:
        bad(("brief",))
    stories = draft.get("stories")
    for n, story in enumerate(stories if isinstance(stories, list) else []):
        if not isinstance(story, dict):
            continue
        body, takeaways, ids = story.get("body"), story.get("takeaways"), story.get("ids")
        if isinstance(body, list) and not 1 <= len(body) <= 6:
            bad(("stories", n, "body"))
        if isinstance(takeaways, list) and len(takeaways) > 5:
            bad(("stories", n, "takeaways"))
        if isinstance(ids, list) and not ids:
            bad(("stories", n, "ids"))
    return out


def draft_errors(exc: ValidationError, draft: dict, settings_topics=None):
    """ValidationError from DraftEdition -> the fixable one-line messages the routine
    sees. Returns (messages, fatal) where fatal means 'stories' itself is unusable and
    nothing below it can be checked."""
    errors = exc.errors() + _length_errors(draft)
    # a wrong-length list is reported once; per-item problems inside it are noise
    list_level = {tuple(e["loc"]) for e in errors
                  if e["type"] in ("too_short", "too_long", "list_type", "missing") and e["loc"]
                  and e["loc"][-1] in ("brief", "body", "takeaways", "ids")}
    messages, seen = [], set()

    def add(msg):
        if msg not in seen:
            seen.add(msg)
            messages.append(msg)

    fatal = False
    for e in errors:
        loc, kind = tuple(e["loc"]), e["type"]
        if _is_list_level(e, list_level):
            continue
        where = _path(loc)
        field = loc[-1] if loc else None
        story_no = loc[1] if len(loc) > 1 and loc[0] == "stories" and isinstance(loc[1], int) else None
        if loc == ("brief",):
            add("brief: must be a list of 3-6 short strings")
        elif len(loc) == 2 and loc[0] == "brief":
            add(f"{where}: must be a string of at least 20 characters")
        elif loc == ("stories",):
            add("stories: must be a non-empty list")
            fatal = True
        elif len(loc) == 2 and loc[0] == "stories":
            add(f"{where}: must be an object")
        elif story_no is not None:
            base = f"stories[{story_no}]"
            story = (draft.get("stories") or [])[story_no] if isinstance((draft.get("stories") or []), list) \
                and story_no < len(draft["stories"]) else {}
            top = loc[2]
            value = story.get(top) if isinstance(story, dict) else None
            if top == "ids":
                add(f"{base}.ids: must be a non-empty list of candidate ids (integers)")
            elif top == "headline" and kind == "string_too_long":
                add(f"{base}.headline: {len(value)} chars -- keep it under 130")
            elif top in ("headline", "dek", "body", "takeaways") and len(loc) == 3 and top in ("body", "takeaways"):
                add(f"{base}.{top}: must be a list of " + ("1-6 paragraphs" if top == "body" else "0-5 strings"))
            elif top in ("body", "takeaways"):
                add(f"{where}: must be a string of at least {80 if top == 'body' else 15} characters")
            elif top in ("headline", "dek"):
                add(f"{base}.{top}: must be a string of at least {15 if top == 'headline' else 40} characters")
            elif top == "event":
                if kind == "string_type" and value is not None and value != "":
                    add(f"{base}.event: {event_problem(value)}")
                else:
                    add(f"{base}.event: missing -- add '- event: ...' with 3-6 lowercase keywords naming the "
                        "event, e.g. 'cloudflare deno acquisition'")
            elif top == "topic":
                add(f"{base}.topic: {value!r} -- must be one of {settings_topics}")
            elif top == "signal":
                add(f"{base}.signal: {value!r} -- must be one of {list(SIGNALS)}")
            else:
                add(f"{where}: {e['msg']}")
        else:
            add(f"{where or 'draft'}: {e['msg']}")
    return messages, fatal


def edition_errors(exc: ValidationError, where="edition"):
    """ValidationError from PublishedEdition -> one-line messages."""
    messages, seen = [], set()

    def add(msg):
        if msg not in seen:
            seen.add(msg)
            messages.append(msg)

    for e in exc.errors():
        loc, kind = tuple(e["loc"]), e["type"]
        if len(loc) == 1:
            if kind == "missing":
                add(f"{where}: missing '{loc[0]}'")
            else:
                add(f"{where}.{loc[0]}: {e['msg']}")
        elif loc[0] == "stories" and len(loc) >= 2:
            at = f"{where}.stories[{loc[1]}]"
            if len(loc) == 2:
                add(f"{at}: must be an object")
                continue
            field = loc[2]
            if field == "url":
                if kind == "missing" or e.get("input") in ("", None):
                    add(f"{at}: missing 'url'")
                add(f"{at}.url: not an http(s) URL")
            elif field in ("headline", "dek", "body", "topic", "signal", "sources") and (
                    kind == "missing" or len(loc) == 3 and kind in ("too_short", "string_too_short")):
                add(f"{at}: missing '{field}'")
            else:
                add(f"{at}.{_path(loc[2:])}: {e['msg']}")
        else:
            add(f"{where}.{_path(loc)}: {e['msg']}")
    return messages
